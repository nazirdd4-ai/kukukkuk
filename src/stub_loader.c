// stub_loader.c — replaces make_launcher.sh's shell self-extractor with a real ELF.
//
// WHY: make_launcher.sh ships a POSIX-sh script that decodes the payload to a temp file on
// disk, chmods it, execs it. That works but (a) it IS a shell script, not "тоже елф бинарник",
// (b) it briefly puts a plaintext copy of @fyxod_cpp on disk — small window, but a window.
// protect.sh's UPX route was tried and shelved: UPX self-decompresses in place, needing the
// SAME process to hold an RWX (or sequential RW->RX re-mapped) page for ITS OWN already-loaded
// code — exactly the shape Android's execmem/W^X SELinux policy exists to deny, and whether it's
// denied is "a per-device/per-ROM question" per that script's own header.
//
// THIS STUB AVOIDS BOTH PROBLEMS BY NOT DOING EITHER THING: it never writes the decrypted bytes
// to a named path (no noexec-mount problem), and it never asks for RWX on ITS OWN pages (no
// execmem problem) — it decrypts into an anonymous memfd (a FILE, as far as the kernel's ELF
// loader is concerned, just not backed by a directory entry), then execve()s that memfd by its
// /proc/self/fd/N path. The actual RX mapping of the decrypted ELF's own segments is done by the
// kernel's normal ELF loader during that execve, the identical path it uses for any binary in
// /system/bin — not by this process self-modifying its own image. That sidesteps the entire
// class of problem UPX hit here, by construction, not by raising cost.
//
// CONSTRAINT this fingerprint leans on (OBSERVED from build.sh): the project already compiles
// with `aarch64-linux-android31-clang++` i.e. targets Android 12 (API 31) and up, well past
// memfd_create()'s API 30 bionic-wrapper floor, so the plain libc call is used below rather than
// a raw syscall() shim for older API levels. If the project's floor ever drops under API 30,
// this needs syscall(SYS_memfd_create, ...) instead — flag that if minSdkVersion changes.
//
// EVIDENCE: the decrypt -> memfd_create -> write -> execve("/proc/self/fd/N") mechanism itself
// was built and run this session on host x86_64 Linux (gcc, glibc) — a trivial ELF was xorshift64-
// encrypted the same way tools/pack_elf.sh does it, embedded, and the resulting stub correctly
// decrypted, launched it via the memfd path, and propagated its exit code. That confirms the
// LOGIC is correct, not a transcription bug. What remains UNVERIFIED is Android/bionic/SELinux
// specifically: no NDK or device was available this session to build+run the aarch64-android
// build (see protect.sh's same disclosure for the general shape of that gap). "The syscalls do
// what the man page says on a stock Linux kernel" and "a specific OEM's SELinux policy allows a
// shell-domain process to execve() a memfd" are different claims — test on-device before shipping
// this over the existing make_launcher.sh route; keep that route as the fallback if a target
// device's policy denies memfd-backed execve (check `logcat -b events | grep avc` for "denied" +
// "execute" if it fails — that's the one realistic failure mode here).
//
// Must stay dependency-free (no BaseMenu/ImGui/touch headers) and small — it is deliberately NOT
// the thing being protected, just the loader standing in front of it; a big stub defeats the
// point and also gives a reverser more to read before reaching the interesting part.

#define _GNU_SOURCE   // syscall() prototype in <unistd.h> on glibc; bionic declares it unconditionally,
                      // but defining this is harmless there and is what makes the host-side sanity
                      // build (this file is portable C, not bionic-only) compile clean on glibc too.
#include <stdint.h>
#include <stddef.h>
#include <sys/syscall.h>
#include <unistd.h>
#include <fcntl.h>
#include <sys/mman.h>
#include <stdio.h>
#include <string.h>
#include <stdlib.h>

#include "stub_blob.h"   // STUB_KEY / STUB_LEN / STUB_BLOB — generated by tools/pack_elf.sh, same
                          // xorshift64-keystream convention as build.sh's PL_KEY/PL_LEN/PL_BLOB
                          // for PAYLOAD, so the decrypt loop below is the one already proven to
                          // round-trip correctly rather than a second, unproven scheme.

static void xorshift64_decrypt(uint8_t* buf, size_t len, uint64_t x) {
    for (size_t i = 0; i < len; ++i) {
        x ^= (x << 13); x ^= (x >> 7); x ^= (x << 17);
        buf[i] ^= (uint8_t)(x >> 24);
    }
}

int main(int argc, char** argv, char** envp) {
    // Decrypt the embedded blob into a heap buffer first — not mmap'd RWX, not written, just a
    // plain RW malloc. Nothing about this process's own executable pages changes.
    uint8_t* out = (uint8_t*)malloc(STUB_LEN);
    if (!out) { fprintf(stderr, "stub: malloc(%zu) failed\n", (size_t)STUB_LEN); return 127; }
    memcpy(out, STUB_BLOB, STUB_LEN);
    xorshift64_decrypt(out, STUB_LEN, STUB_KEY);

    // MFD_CLOEXEC deliberately NOT set: we need this fd to still be open in THIS process at the
    // moment we call execve() referencing it by path below. (It plays no role after that: the
    // new program image replaces this one entirely.)
    int fd = (int)syscall(SYS_memfd_create, "", 0);
    if (fd < 0) { perror("stub: memfd_create"); free(out); return 127; }

    size_t off = 0;
    while (off < (size_t)STUB_LEN) {
        ssize_t n = write(fd, out + off, STUB_LEN - off);
        if (n < 0) { perror("stub: write(memfd)"); close(fd); free(out); return 127; }
        off += (size_t)n;
    }
    // Zero the heap copy now that it's in the memfd — not a secrecy boundary (same honesty as
    // this project's other "ships in the binary" disclosures), just hygiene: no reason to leave
    // a second plaintext copy sitting in the heap once the memfd has it.
    memset(out, 0, STUB_LEN);
    free(out);

    char path[64];
    snprintf(path, sizeof(path), "/proc/self/fd/%d", fd);

    // argv[0] stays as the stub's own argv[0] (what the caller/shell already typed), not the
    // memfd path — cosmetic, but matches what execve'ing a normal file would show in argv[0].
    execve(path, argv, envp);

    // Only reached if execve() itself failed (ENOEXEC, EACCES from an SELinux denial, etc.) —
    // see the UNVERIFIED note above for what EACCES here most likely means.
    perror("stub: execve(memfd)");
    close(fd);
    return 127;
}
