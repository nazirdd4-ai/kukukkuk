#!/usr/bin/env python3
"""gen_sectkey.py — generates include/sectkey.h: a fresh random 32-byte key
and 12-byte nonce for sectcrypt.hpp's PCODE section encryption.

Must run BEFORE compiling a SECT_PROTECT=1 build (sectkey.h is #include'd by
sectcrypt.hpp, needed at compile time to embed the key the decrypt stub
uses) and its output (the hex printed on the last line) is what build.sh
feeds to tools/encrypt_section.py after linking, so both sides encrypt and
decrypt with the same bytes.

Usage: python3 tools/gen_sectkey.py <path/to/include/sectkey.h>
Prints "SECT_KEY_HEX=<64 hex chars> SECT_NONCE_HEX=<24 hex chars>" on stdout
— build.sh greps these two lines back out rather than re-deriving them from
the generated header, same reasoning build.sh already gives for pulling
ENC_KEY_HEX out of enc_strings.hpp instead of hand-copying it.

Re-run this for every SECT_PROTECT build you don't want sharing a key with a
previous one — nothing here persists a key across runs, each invocation is
a fresh os.urandom() draw.
"""
import os
import sys


def main():
    if len(sys.argv) != 2:
        print("usage: gen_sectkey.py <path/to/include/sectkey.h>", file=sys.stderr)
        sys.exit(1)
    out_path = sys.argv[1]

    key = os.urandom(32)
    nonce = os.urandom(12)

    def carr(b):
        return ", ".join("0x%02x" % x for x in b)

    with open(out_path, "w") as f:
        f.write(
            "// generated by tools/gen_sectkey.py — do not edit, do not commit\n"
            "// (this key is what SECT_PROTECT builds ship with baked in; see\n"
            "// integrity.h's header for why that's not a contradiction: a local\n"
            "// secret can't be hidden from the binary that carries it either way)\n"
            "#pragma once\n"
            "#include <stdint.h>\n\n"
            f"inline constexpr uint8_t SECT_KEY[32] = {{ {carr(key)} }};\n"
            f"inline constexpr uint8_t SECT_NONCE[12] = {{ {carr(nonce)} }};\n"
        )

    print(f"SECT_KEY_HEX={key.hex()} SECT_NONCE_HEX={nonce.hex()}")
    print(f"[+] wrote {out_path}", file=sys.stderr)


if __name__ == "__main__":
    main()
