// fault-safe read: write() from the source range into a pipe returns EFAULT instead of crashing the game on a bad pointer
static int g_probe[2] = {-1, -1};
static bool safeRead(const void* src, void* dst, size_t n) {
    if (n == 0 || n > 256 || (uintptr_t)src < 0x10000) return false;
    if (g_probe[0] < 0) {
        if (pipe(g_probe) != 0) { g_probe[0] = g_probe[1] = -1; return false; }
        for (int i = 0; i < 2; i++) fcntl(g_probe[i], F_SETFL, fcntl(g_probe[i], F_GETFL) | O_NONBLOCK);
    }
    ssize_t w = write(g_probe[1], src, n);
    if (w <= 0) return false;
    char tmp[256]; ssize_t r = read(g_probe[0], tmp, (size_t)w);
    if (w != (ssize_t)n || r != (ssize_t)n) return false;
    memcpy(dst, tmp, n); return true;
}
template <class T> static bool rd(uintptr_t a, T& v) { return safeRead((const void*)a, &v, sizeof(T)); }

static bool klassName(void* k, char* out, size_t cap) {
    uintptr_t np = 0;
    if (!rd((uintptr_t)k + off2::klass_name, np) || np < 0x10000) return false;
    size_t i = 0;
    for (; i + 1 < cap; i++) { char ch; if (!rd(np + i, ch)) return false; out[i] = ch; if (!ch) return true; }
    out[i] = 0; return true;
}
