// lock screen touch handling — called from runOverlay evdev loop
// Returns true if the touch was consumed.
static bool lockScreenTouch(int action, float tx, float ty) {
    if (g_licensed) return false;
    float u = g_menu.uiScale;
    float W = (float)g_scrW;
    float pw = std::min(W * 0.92f, 900.f);
    float ph = (float)g_scrH * 0.72f;
    float px = (W - pw) * 0.5f, py = ((float)g_scrH - ph) * 0.5f;
    float bh2 = 44.f * u;
    float kbX = px + 28.f * u, kbTop = py + 60.f * u + bh2 + 16.f * u;
    float kbW  = pw - 56.f * u;
    float kbKW = kbW / 10.f - 4.f * u;
    float kbKH = kbKW * 0.9f;
    static const char* rows[4] = {"1234567890", "qwertyuiop", "asdfghjkl-", "zxcvbnm_@."};

    if (action != 0 && action != 1) return true;   // only down/up
    if (action == 1) return true;                   // release: no action needed

    // key rows
    for (int r = 0; r < 4; r++) {
        float rowY2 = kbTop + r * (kbKH + 6.f * u);
        for (int i = 0; rows[r][i]; i++) {
            float kx2 = kbX + i * (kbKW + 4.f * u);
            if (tx >= kx2 && tx <= kx2 + kbKW && ty >= rowY2 && ty <= rowY2 + kbKH) {
                char ch = rows[r][i];
                if (g_kbShift && ch >= 'a' && ch <= 'z') ch = (char)(ch - 32);
                char lab[2] = {ch, 0}; kbAppend(lab); g_kbShift = false;
                return true;
            }
        }
    }

    // control row
    float ctrlY = kbTop + 4 * (kbKH + 6.f * u);
    float ctrlW = (kbW - 3.f * 4.f * u) / 4.f;
    // shift
    float sx = kbX, se = sx + ctrlW;
    if (tx >= sx && tx <= se && ty >= ctrlY && ty <= ctrlY + kbKH) { g_kbShift = !g_kbShift; return true; }
    // space
    float spx = kbX + ctrlW + 4.f * u, spe = spx + ctrlW * 2.f + 4.f * u;
    if (tx >= spx && tx <= spe && ty >= ctrlY && ty <= ctrlY + kbKH) { kbAppend(" "); return true; }
    // del
    float dx2 = kbX + ctrlW * 3.f + 8.f * u, de2 = dx2 + ctrlW * 0.5f;
    if (tx >= dx2 && tx <= de2 && ty >= ctrlY && ty <= ctrlY + kbKH) {
        size_t n = strlen(g_keyBuf); if (n) g_keyBuf[n - 1] = 0; return true;
    }
    // clr
    float cx2 = kbX + ctrlW * 3.5f + 10.f * u, ce2 = cx2 + ctrlW * 0.5f;
    if (tx >= cx2 && tx <= ce2 && ty >= ctrlY && ty <= ctrlY + kbKH) { g_keyBuf[0] = 0; return true; }

    // unlock button
    float unlockY = ctrlY + kbKH + 8.f * u;
    float ulW = pw - 56.f * u;
    if (tx >= kbX && tx <= kbX + ulW && ty >= unlockY && ty <= unlockY + kbKH * 1.1f) {
        if (g_keyBuf[0] && !g_licBusy) licStart(g_keyBuf, false);
        return true;
    }
    return true;   // consume all touches while locked
}

// ── ESP via Gfx ──────────────────────────────────────────────────────────
static void drawEsp() {
    if (!g_cfg.esp || g_cnt <= 0 || g_sw <= 0 || g_sh <= 0) return;
    float kx = (float)g_scrW / (float)g_sw, ky = (float)g_scrH / (float)g_sh;
    float hs = g_cfg.headH / off::HEAD_H;
    float lw = g_cfg.lineWidth;

    for (int i = 0; i < g_cnt; i++) {
        Ent& e = g_ents[i];
        if (!e.alive || e.dist > g_cfg.maxDist) continue;
        if (e.team && !g_cfg.team) continue;

        float fx = e.fx * kx, fy = ((float)g_sh - e.fy) * ky;
        float hx = e.hx * kx, hy0 = ((float)g_sh - e.hy) * ky;
        float hy = fy - (fy - hy0) * hs;
        float h = fy - hy; if (h < 4.f) continue;
        float w = h * 0.45f, cx = (fx + hx) * 0.5f;
        float x0 = cx - w * 0.5f, x1 = cx + w * 0.5f;

        float* c = e.team ? g_cfg.colTeam : g_cfg.colEnemy;
        Col col = rgba((int)(c[0]*255),(int)(c[1]*255),(int)(c[2]*255));
        Col blk = rgba(0,0,0,200);

        if (g_cfg.lines) g_gfx.line((float)g_scrW*0.5f,(float)g_scrH, fx, fy, 1.5f, col);
        if (g_cfg.box) {
            float cw = (x1-x0)*0.25f, ch = h*0.18f;
            auto corner = [&](float bx2, float by2, float sx, float sy) {
                g_gfx.line(bx2, by2, bx2+sx*cw, by2, lw+2.f, blk);
                g_gfx.line(bx2, by2, bx2, by2+sy*ch, lw+2.f, blk);
                g_gfx.line(bx2, by2, bx2+sx*cw, by2, lw, col);
                g_gfx.line(bx2, by2, bx2, by2+sy*ch, lw, col);
            };
            corner(x0, hy, +1.f, +1.f);
            corner(x1, hy, -1.f, +1.f);
            corner(x0, fy, +1.f, -1.f);
            corner(x1, fy, -1.f, -1.f);
        }
        if (g_cfg.skeleton) {
            Col blkSkel = rgba(0,0,0,160);
            if (e.jmask) {
                struct P2 { float x, y; };
                auto JP = [&](int j, P2& q) -> bool {
                    if (!(e.jmask & (1u << j))) return false;
                    q = {e.jx[j]*kx, ((float)g_sh-e.jy[j])*ky}; return true;
                };
                static const int B[][2] = {
                    {J_NECK, J_CHEST}, {J_CHEST, J_HIPS},
                    {J_CHEST, J_LSH}, {J_LSH, J_LEL}, {J_LEL, J_LHA},
                    {J_CHEST, J_RSH}, {J_RSH, J_REL}, {J_REL, J_RHA},
                    {J_HIPS, J_LHIP}, {J_LHIP, J_LKN}, {J_LKN, J_LFT},
                    {J_HIPS, J_RHIP}, {J_RHIP, J_RKN}, {J_RKN, J_RFT}};
                P2 pa, pb, jh, jn, jc;
                bool hasH = JP(J_HEAD, jh), hasN = JP(J_NECK, jn), hasC = JP(J_CHEST, jc);
                for (int pass = 0; pass < 2; pass++) {
                    Col lc = pass == 0 ? blkSkel : col; float lt = pass == 0 ? lw+2.f : lw;
                    for (auto& bb : B) { P2 pa2, pb2; if (JP(bb[0],pa2)&&JP(bb[1],pb2)) g_gfx.line(pa2.x,pa2.y,pb2.x,pb2.y,lt,lc); }
                    if (hasH && hasN) g_gfx.line(jn.x,jn.y,jh.x,jh.y,lt,lc);
                    else if (hasH && hasC) g_gfx.line(jc.x,jc.y,jh.x,jh.y,lt,lc);
                    if (hasH) {
                        float r = hasN ? sqrtf((jh.x-jn.x)*(jh.x-jn.x)+(jh.y-jn.y)*(jh.y-jn.y))*0.8f : h*0.07f;
                        if (r < 3.f) r = 3.f;
                        for (int seg=0;seg<16;seg++) {
                            float a0=seg*6.2832f/16.f, a1=(seg+1)*6.2832f/16.f;
                            g_gfx.line(jh.x+cosf(a0)*r,jh.y+sinf(a0)*r,jh.x+cosf(a1)*r,jh.y+sinf(a1)*r,lt,lc);
                        }
                    }
                }
            } else {
                float hipY = hy+h*0.52f, shY = hy+h*0.24f, hr = h*0.07f;
                for (int pass = 0; pass < 2; pass++) {
                    Col lc = pass == 0 ? blkSkel : col; float lt = pass == 0 ? lw+2.f : lw;
                    for (int seg=0;seg<16;seg++) {
                        float a0=seg*6.2832f/16.f, a1=(seg+1)*6.2832f/16.f;
                        g_gfx.line(cx+cosf(a0)*hr,hy+hr+sinf(a0)*hr,cx+cosf(a1)*hr,hy+hr+sinf(a1)*hr,lt,lc);
                    }
                    g_gfx.line(cx,hy+hr*2.f,cx,hipY,lt,lc);
                    g_gfx.line(cx-w*0.55f,hy+h*0.45f,cx,shY,lt,lc);
                    g_gfx.line(cx+w*0.55f,hy+h*0.45f,cx,shY,lt,lc);
                    g_gfx.line(cx,hipY,cx-w*0.28f,fy,lt,lc);
                    g_gfx.line(cx,hipY,cx+w*0.28f,fy,lt,lc);
                }
            }
        }
        if (g_cfg.hp && e.hpMax > 1.f) {
            float f = e.hp/e.hpMax; f = f<0?0:(f>1?1:f);
            float bx0=x0, bx1=x1, bby=fy+5.f, bbh=4.f;
            g_gfx.rect(bx0-1,bby-1,bx1-bx0+2,bbh+2,0.f,blk);
            g_gfx.rect(bx0,bby,(bx1-bx0)*f,bbh,0.f,rgba((int)(255*(1.f-f)),(int)(220*f),30));
        }
        if (g_cfg.names && e.name[0]) {
            float fs2 = 14.f;
            float tw2 = g_gfx.textWidth(e.name, fs2);
            float nx2 = cx - tw2*0.5f, ny2 = hy - fs2 - 4.f;
            g_gfx.text(nx2+1.f, ny2+1.f, e.name, fs2, rgba(0,0,0,220));
            g_gfx.text(nx2, ny2, e.name, fs2, rgba(255,255,255));
        }
        if (g_cfg.dist) {
            char t[24]; snprintf(t, sizeof(t), "%dm", (int)e.dist);
            float fs3 = 13.f;
            float tw3 = g_gfx.textWidth(t, fs3);
            g_gfx.text(cx - tw3*0.5f, fy+3.f, t, fs3, rgba(255,255,255));
        }
    }
}

