// ── license check (HOST side only) ───────────────────────────────────────────
// POST https://license-validator.gosthtoster.workers.dev/  {"licenseKey":"<KEY>"} over TLS.
// Uses Android's own libssl.so (BoringSSL, classic OpenSSL symbol names) via dlopen,
// so no TLS lib needs to be linked or bundled. Needs libssl.so/libcrypto.so on-device
// (stock on every Android) and internet access for the root shell.
namespace lic {
    inline const char*    SRV_HOST()     { return get_STR_SRV_HOST(); } // not HOST: clashes with NDK linux/input-event-codes.h
    inline const char*    SRV_HOST_ALT() { return get_STR_SRV_HOST_ALT(); } // fallback when SRV_HOST is DPI-blocked (RU etc.) — see build_obus.yml
    constexpr int         IO_TIMEOUT_MS = 4000;    // per connect / handshake / read / write step
    constexpr int         TOTAL_MS      = 10000;   // wall-clock cap for one whole request (excluding DNS)
    constexpr const char* PATH     = "/";                                           // worker does not route by path
    inline const char*    KEY_PATH() { return get_STR_KEY_PATH(); }                  // not KEY_FILE: clashes with the same header (KEY_FILE=144)
}

static int64_t licNowMs() {
    timespec ts{}; clock_gettime(CLOCK_MONOTONIC, &ts);
    return (int64_t)ts.tv_sec * 1000 + ts.tv_nsec / 1000000;
}

// connect with a hard deadline, then switch back to blocking mode with SO_RCVTIMEO/SO_SNDTIMEO so that
// SSL_connect / SSL_write / SSL_read on this fd cannot block forever either.
static int tcpConnect(const char* host, int port, int timeoutMs) {
    addrinfo hints{}; hints.ai_family = AF_UNSPEC; hints.ai_socktype = SOCK_STREAM;
    addrinfo* res = nullptr;
    char portStr[8]; snprintf(portStr, sizeof(portStr), "%d", port);
    if (getaddrinfo(host, portStr, &hints, &res) != 0 || !res) return -1;
    int fd = -1;
    for (addrinfo* p = res; p; p = p->ai_next) {
        fd = socket(p->ai_family, p->ai_socktype, p->ai_protocol);
        if (fd < 0) continue;
        int fl = fcntl(fd, F_GETFL, 0);
        fcntl(fd, F_SETFL, fl | O_NONBLOCK);
        int rc = connect(fd, p->ai_addr, p->ai_addrlen);
        if (rc != 0 && errno == EINPROGRESS) {
            pollfd pf{}; pf.fd = fd; pf.events = POLLOUT;
            int pr = poll(&pf, 1, timeoutMs);
            int err = 1; socklen_t el = sizeof(err);
            if (pr == 1 && getsockopt(fd, SOL_SOCKET, SO_ERROR, &err, &el) == 0 && err == 0) rc = 0; else rc = -1;
        }
        if (rc == 0) {
            fcntl(fd, F_SETFL, fl);
            timeval tv{}; tv.tv_sec = timeoutMs / 1000; tv.tv_usec = (timeoutMs % 1000) * 1000;
            setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &tv, sizeof(tv));
            setsockopt(fd, SOL_SOCKET, SO_SNDTIMEO, &tv, sizeof(tv));
            break;
        }
        close(fd); fd = -1;
    }
    freeaddrinfo(res);
    return fd;
}

// true once the HTTP response is fully received (Content-Length reached or chunked terminator seen),
// so the read loop does not have to wait for the server to close the connection. buf is NUL-terminated.
static bool httpComplete(const char* buf, size_t len) {
    const char* he = strstr(buf, "\r\n\r\n");
    if (!he) return false;
    size_t hdrLen = (size_t)(he - buf) + 4;
    for (const char* p = buf; p < he; ++p)
        if ((p == buf || p[-1] == '\n') && !strncasecmp(p, "content-length:", 15))
            return len - hdrLen >= (size_t)strtoul(p + 15, nullptr, 10);
    return len >= 5 && !memcmp(buf + len - 5, "0\r\n\r\n", 5);
}
// ---- on-device libssl (BoringSSL), resolved by hand. Entry points differ between Android builds, so each
// one has fallbacks and a failed resolve reports the exact missing names in the log.
struct SslApi {
    void* (*TLS_client_method)();
    void* (*SSL_CTX_new)(void*);
    void  (*SSL_CTX_set_verify)(void*, int, void*);
    void  (*SSL_CTX_free)(void*);
    void* (*SSL_new)(void*);
    int   (*SSL_set_fd)(void*, int);
    int   (*SSL_set_tlsext_host_name)(void*, const char*);
    long  (*SSL_ctrl)(void*, int, long, void*);
    int   (*SSL_connect)(void*);
    int   (*SSL_write)(void*, const void*, int);
    int   (*SSL_read)(void*, void*, int);
    int   (*SSL_shutdown)(void*);
    void  (*SSL_free)(void*);
};

static void* symAny(void* h, const char* a, const char* b, const char* c) {
    void* p = dlsym(h, a);
    if (!p && b) p = dlsym(h, b);
    if (!p && c) p = dlsym(h, c);
    return p;
}

static void addMiss(char* miss, size_t cap, const char* name) {
    size_t n = strlen(miss);
    if (n + strlen(name) + 2 < cap) { strcat(miss, name); strcat(miss, " "); }
}

static bool sslResolve(void* h, SslApi& a, char* miss, size_t cap) {
    miss[0] = 0;
    a.TLS_client_method        = (decltype(a.TLS_client_method))       symAny(h, "TLS_client_method", "TLS_method", "SSLv23_client_method");
    a.SSL_CTX_new              = (decltype(a.SSL_CTX_new))             symAny(h, "SSL_CTX_new", nullptr, nullptr);
    a.SSL_CTX_set_verify       = (decltype(a.SSL_CTX_set_verify))      symAny(h, "SSL_CTX_set_verify", nullptr, nullptr);
    a.SSL_CTX_free             = (decltype(a.SSL_CTX_free))            symAny(h, "SSL_CTX_free", nullptr, nullptr);
    a.SSL_new                  = (decltype(a.SSL_new))                 symAny(h, "SSL_new", nullptr, nullptr);
    a.SSL_set_fd               = (decltype(a.SSL_set_fd))              symAny(h, "SSL_set_fd", nullptr, nullptr);
    a.SSL_set_tlsext_host_name = (decltype(a.SSL_set_tlsext_host_name))symAny(h, "SSL_set_tlsext_host_name", nullptr, nullptr);
    a.SSL_ctrl                 = (decltype(a.SSL_ctrl))                symAny(h, "SSL_ctrl", nullptr, nullptr);
    a.SSL_connect              = (decltype(a.SSL_connect))             symAny(h, "SSL_connect", nullptr, nullptr);
    a.SSL_write                = (decltype(a.SSL_write))               symAny(h, "SSL_write", nullptr, nullptr);
    a.SSL_read                 = (decltype(a.SSL_read))                symAny(h, "SSL_read", nullptr, nullptr);
    a.SSL_shutdown             = (decltype(a.SSL_shutdown))            symAny(h, "SSL_shutdown", nullptr, nullptr);
    a.SSL_free                 = (decltype(a.SSL_free))                symAny(h, "SSL_free", nullptr, nullptr);
    // required; set_verify / shutdown / frees are optional (a leak or a skipped close does not matter here)
    if (!a.TLS_client_method) addMiss(miss, cap, "TLS_client_method");
    if (!a.SSL_CTX_new)      addMiss(miss, cap, "SSL_CTX_new");
    if (!a.SSL_new)          addMiss(miss, cap, "SSL_new");
    if (!a.SSL_set_fd)       addMiss(miss, cap, "SSL_set_fd");
    if (!a.SSL_connect)      addMiss(miss, cap, "SSL_connect");
    if (!a.SSL_write)        addMiss(miss, cap, "SSL_write");
    if (!a.SSL_read)         addMiss(miss, cap, "SSL_read");
    if (!a.SSL_set_tlsext_host_name && !a.SSL_ctrl) addMiss(miss, cap, "SSL_set_tlsext_host_name/SSL_ctrl");   // SNI is mandatory on Cloudflare
    return miss[0] == 0;
}

// reqBody == nullptr -> GET, otherwise POST with a JSON body.
static bool httpsRequest(const char* host, const char* path, const char* reqBody, char* out, size_t outCap) {
    const char* const LIBS[] = { get_STR_LIBSSL_0(), get_STR_LIBSSL_1(), get_STR_LIBSSL_2() };
    SslApi a{};
    bool have = false;
    for (const char* lib : LIBS) {
        void* h = dlopen(lib, RTLD_NOW);
        if (!h) { EPRINT("license: dlopen %s failed\n", lib); continue; }
        char miss[192];
        if (sslResolve(h, a, miss, sizeof(miss))) { have = true; EPRINT("license: using %s\n", lib); break; }
        EPRINT("license: %s missing: %s\n", lib, miss);
    }
    if (!have) { EPRINT("license: no usable libssl\n"); return false; }

    // build the request first: nothing is opened yet, so early-outs need no cleanup
    char req[768];
    int n;
    if (reqBody)
        n = snprintf(req, sizeof(req),
                     "POST %s HTTP/1.1\r\nHost: %s\r\nConnection: close\r\nUser-Agent: %s\r\n"
                     "Content-Type: application/json\r\nContent-Length: %zu\r\n\r\n%s",
                     path, host, get_STR_LOG_TAG(), strlen(reqBody), reqBody);
    else
        n = snprintf(req, sizeof(req),
                     "GET %s HTTP/1.1\r\nHost: %s\r\nConnection: close\r\nUser-Agent: %s\r\n\r\n",
                     path, host, get_STR_LOG_TAG());
    if (n <= 0 || n >= (int)sizeof(req)) { EPRINT("license: request too large\n"); return false; }

    int64_t deadline = licNowMs() + lic::TOTAL_MS;
    int fd = tcpConnect(host, 443, lic::IO_TIMEOUT_MS);
    if (fd < 0) { EPRINT("license: tcp connect failed (no network?)\n"); return false; }

    void* ctx = a.SSL_CTX_new(a.TLS_client_method());
    if (!ctx) { EPRINT("license: SSL_CTX_new failed\n"); close(fd); return false; }
    // VERIFY_NONE: a MITM can still answer with an HTTP 200 and arbitrary bytes, but can no
    // longer flip a rejection into an accept — licenseCheck() now requires a valid HMAC sig
    // over the response (verifyLicenseSig()), which needs STR_SIG_KEY, not just network
    // position. Full CA verification would additionally stop traffic *inspection* (the key
    // value itself leaking to a MITM) — still worth doing, lower priority than the sig was.
    if (a.SSL_CTX_set_verify) a.SSL_CTX_set_verify(ctx, 0 /*SSL_VERIFY_NONE*/, nullptr);
    void* ssl = a.SSL_new(ctx);
    if (!ssl) { EPRINT("license: SSL_new failed\n"); if (a.SSL_CTX_free) a.SSL_CTX_free(ctx); close(fd); return false; }
    a.SSL_set_fd(ssl, fd);
    if (a.SSL_set_tlsext_host_name) a.SSL_set_tlsext_host_name(ssl, host);
    else a.SSL_ctrl(ssl, 55 /*SSL_CTRL_SET_TLSEXT_HOSTNAME*/, 0 /*TLSEXT_NAMETYPE_host_name*/, (void*)host);
    if (a.SSL_connect(ssl) != 1) {
        EPRINT("license: TLS handshake failed\n");
        if (a.SSL_free) a.SSL_free(ssl);
        if (a.SSL_CTX_free) a.SSL_CTX_free(ctx);
        close(fd); return false;
    }

    bool wrote = a.SSL_write(ssl, req, n) == n;
    size_t total = 0;
    if (wrote) {
        while (total + 1 < outCap && licNowMs() < deadline) {
            int r = a.SSL_read(ssl, out + total, (int)(outCap - 1 - total));
            if (r <= 0) break;                      // EOF, error, or SO_RCVTIMEO expiry
            total += (size_t)r;
            out[total] = 0;
            if (httpComplete(out, total)) break;    // do not wait for the peer to close
        }
    } else EPRINT("license: request write failed\n");
    out[total] = 0;
    if (a.SSL_shutdown) a.SSL_shutdown(ssl);
    if (a.SSL_free) a.SSL_free(ssl);
    if (a.SSL_CTX_free) a.SSL_CTX_free(ctx);
    close(fd);
    return total > 0;
}

enum LicResult { LIC_NONE = 0, LIC_VALID, LIC_REJECTED, LIC_NETERR };

// lower-hex -> bytes; returns false on odd length or a non-hex char (truncated/corrupt field,
// not a signature to trust further). outCap must be >= hexLen/2.
static bool hexDecode(const char* hex, size_t hexLen, uint8_t* out, size_t outCap) {
    if (hexLen % 2 || hexLen / 2 > outCap) return false;
    for (size_t i = 0; i < hexLen; i += 2) {
        int hi = -1, lo = -1;
        char c0 = hex[i], c1 = hex[i+1];
        if (c0 >= '0' && c0 <= '9') hi = c0 - '0'; else if (c0 >= 'a' && c0 <= 'f') hi = c0 - 'a' + 10; else if (c0 >= 'A' && c0 <= 'F') hi = c0 - 'A' + 10;
        if (c1 >= '0' && c1 <= '9') lo = c1 - '0'; else if (c1 >= 'a' && c1 <= 'f') lo = c1 - 'a' + 10; else if (c1 >= 'A' && c1 <= 'F') lo = c1 - 'A' + 10;
        if (hi < 0 || lo < 0) return false;
        out[i/2] = (uint8_t)((hi << 4) | lo);
    }
    return true;
}

// Extracts the value of "field":"..." (a quoted hex string, no escapes expected) from a flat
// JSON object. Not a general JSON parser — matches this project's own worker output, which is
// JSON.stringify() on a flat object (see STRINGS["STR_SRV_HOST"] comment above: compact, no
// spaces). Returns nullptr if not found; *outLen is the value length.
static const char* jsonFindHexField(const char* body, const char* field, size_t* outLen) {
    char needle[32];
    snprintf(needle, sizeof(needle), "\"%s\":\"", field);
    const char* p = strstr(body, needle);
    if (!p) return nullptr;
    p += strlen(needle);
    const char* end = p;
    while (*end && *end != '"') ++end;
    *outLen = (size_t)(end - p);
    return p;
}

// Server must sign exactly "<licenseKey>|<0 or 1>" with HMAC-SHA256 under the same secret as
// STR_SIG_KEY (worker-side env var, 64 hex chars / 32 bytes — generate with
// `python3 -c "import os;print(os.urandom(32).hex())"`, same convention as ENC_KEY) and return
// it as "sig":"<64 lowercase hex chars>" alongside "valid". See cloudflare_worker_sig_snippet.js
// for the worker-side half of this.
static bool verifyLicenseSig(const char* key, bool valid, const char* body) {
    size_t sigLen = 0;
    const char* sigHex = jsonFindHexField(body, "sig", &sigLen);
    if (!sigHex || sigLen != 64) { EPRINT("license: missing/malformed sig field\n"); return false; }
    uint8_t sig[32];
    if (!hexDecode(sigHex, sigLen, sig, sizeof(sig))) { EPRINT("license: sig not valid hex\n"); return false; }

    char msg[160];
    int n = snprintf(msg, sizeof(msg), "%s|%c", key, valid ? '1' : '0');
    if (n <= 0 || n >= (int)sizeof(msg)) return false;

    size_t sigKeyHexLen = strlen(get_STR_SIG_KEY());
    uint8_t sigKey[32];
    if (!hexDecode(get_STR_SIG_KEY(), sigKeyHexLen, sigKey, sizeof(sigKey))) {
        EPRINT("license: bad STR_SIG_KEY (build misconfigured)\n"); return false;
    }

    uint8_t expected[32];
    hmac::sha256(sigKey, sizeof(sigKey), (const uint8_t*)msg, (size_t)n, expected);
    return hmac::constTimeEq(sig, expected, 32);
}

static LicResult licenseCheck(const char* key) {
    if (!key || !key[0]) return LIC_REJECTED;
    // the key is spliced into JSON by hand: reject anything that would break the string
    for (const char* p = key; *p; ++p)
        if ((unsigned char)*p < 0x20 || *p == '"' || *p == '\\') { EPRINT("license: bad character in key\n"); return LIC_REJECTED; }

    char reqBody[256];
    int bn = snprintf(reqBody, sizeof(reqBody), "{\"licenseKey\":\"%s\"}", key);
    if (bn <= 0 || bn >= (int)sizeof(reqBody)) { EPRINT("license: key too long\n"); return LIC_REJECTED; }

    char resp[4096];
    // RU-style DPI blocks by SNI, not by destination IP, so the fallback here must be a second
    // hostname (a different domain/zone not on the blocklist), not just another IP for the same
    // name -- swapping only the IP while keeping the same SNI/Host sails straight past nothing.
    const char* hosts[2] = { lic::SRV_HOST(), lic::SRV_HOST_ALT() };
    bool ok = false;
    for (int hi = 0; hi < 2; ++hi) {
        if (!hosts[hi] || !hosts[hi][0]) continue;
        if (hi == 1) EPRINT("license: primary host failed, trying fallback\n");
        if (httpsRequest(hosts[hi], lic::PATH, reqBody, resp, sizeof(resp))) { ok = true; break; }
    }
    if (!ok) { EPRINT("license: request failed\n"); return LIC_NETERR; }

    bool httpOk = !strncmp(resp, "HTTP/1.1 2", 10) || !strncmp(resp, "HTTP/1.0 2", 10);
    char* body = strstr(resp, "\r\n\r\n"); body = body ? body + 4 : resp;
    // worker answers JSON.stringify({valid:true,...}) -> compact, no spaces
    bool claimedValid = httpOk && strstr(body, "\"valid\":true") != nullptr;
    // claimedValid alone used to be the whole check — that's anyone who can put bytes in front
    // of SSL_read() (MITM under VERIFY_NONE below, or a Frida hook on SSL_read itself, which
    // VERIFY_NONE->VERIFY_PEER would not even stop since it runs after TLS decrypts). The sig
    // check below means a forged pass needs STR_SIG_KEY, not just control of the response bytes.
    bool valid = claimedValid && verifyLicenseSig(key, true, body);
    if (!valid) EPRINT("license: rejected (%.80s)\n", body);
    return valid ? LIC_VALID : LIC_REJECTED;
}
static const char* keyPath() {
    static char p[512];
    dataJoin(p, sizeof(p), ".fyxod");
    return p;
}
static void loadSavedKey(char* out, size_t cap) {
    out[0] = 0;
    FILE* f = fopen(keyPath(), "r"); if (!f) return;
    if (fgets(out, (int)cap, f)) {
        size_t n = strlen(out);
        while (n && (out[n - 1] == '\n' || out[n - 1] == '\r')) out[--n] = 0;
    }
    fclose(f);
}
static void saveKey(const char* key) {
    FILE* f = fopen(keyPath(), "w"); if (!f) return;
    fputs(key, f); fclose(f); chmod(keyPath(), 0600);
}

// The check runs on a worker thread; the render loop only polls the result, so the overlay never blocks on the network.
// A generation counter lets the UI abandon a worker that is stuck (e.g. in getaddrinfo, which has no timeout of its own).
struct LicJob { char key[128]; int gen; };
static std::atomic<int>     g_licGen{0};
static std::atomic<int>     g_licRes{LIC_NONE};   // result of the job whose gen == g_licGen
// g_licBusy is defined earlier, next to g_keyBuf (read by render code before this point)
static bool                 g_licAuto = false;     // the running job checks the saved key, not a typed one
static int64_t              g_licT0   = 0;
static char                 g_licKeyUsed[128] = {};
constexpr int64_t           LIC_UI_GIVEUP_MS = 25000;

static void* licWorker(void* arg) {
    LicJob* j = (LicJob*)arg;
    LicResult r = licenseCheck(j->key);
    if (j->gen == g_licGen.load()) g_licRes.store((int)r);   // stale job: result dropped
    delete j;
    return nullptr;
}

static bool licStart(const char* key, bool autoCheck) {
    LicJob* j = new LicJob{}; snprintf(j->key, sizeof(j->key), "%s", key);
    snprintf(g_licKeyUsed, sizeof(g_licKeyUsed), "%s", key);
    j->gen = g_licGen.fetch_add(1) + 1;
    g_licRes.store(LIC_NONE);
    pthread_t t;
    if (pthread_create(&t, nullptr, licWorker, j) != 0) { delete j; g_licStatus = "cannot start check thread"; return false; }
    pthread_detach(t);
    g_licBusy = true; g_licAuto = autoCheck; g_licT0 = licNowMs(); g_licStatus.clear();
    return true;
}

// called once per frame from the render loop
static void licPoll() {
    if (!g_licBusy) return;
    int r = g_licRes.load();
    if (r == LIC_NONE) {
        if (licNowMs() - g_licT0 > LIC_UI_GIVEUP_MS) {
            g_licGen.fetch_add(1);                 // orphan the stuck worker
            g_licBusy = false;
            if (g_licAuto) g_keyBuf[0] = 0;
            g_licStatus = "license server timeout";
        }
        return;
    }
    g_licBusy = false;
    if (r == LIC_VALID) { saveKey(g_licKeyUsed); g_licensed = true; g_licStatus.clear(); }
    else {
        if (g_licAuto) g_keyBuf[0] = 0;           // do not prefill a saved key that just failed
        g_licStatus = (r == LIC_NETERR) ? "no connection to license server" : "invalid key";
    }
}

// resolves the libcheat.so path the way main() used to (argv override / embedded / next to the binary)
static bool resolveLib(int argc, char** argv, bool overlayOnly, char* lib, size_t cap, bool& emb) {
    emb = false;
    if (overlayOnly) return true;
    if (argc > 1) { snprintf(lib, cap, "%s", argv[1]); return true; }
    #ifdef EMBED_PAYLOAD
    emb = true; return true;
    #else
    char self[512] = {};
    ssize_t r = readlink("/proc/self/exe", self, sizeof(self) - 1);
    if (r <= 0) { perror("readlink"); return false; }
    char* sl = strrchr(self, '/');
    if (sl) { *sl = 0; snprintf(lib, cap, "%s/%s", self, get_STR_LIBCHEAT()); } else snprintf(lib, cap, "./%s", get_STR_LIBCHEAT());
    return true;
    #endif
}

// usage: @fyxod_cpp [libcheat.so path]   |   @fyxod_cpp --overlay   (skip injection)
// injection now happens lazily, once the license lock screen accepts a key — the overlay (and the key
// input it draws) has to be up before that can happen at all.
// ── evdev touch reader ────────────────────────────────────────────────────
// Reads raw MT events from /dev/input/eventN (opened by TouchHelperA via
// Touch_Init, which returns the fd through its last parameter when != nullptr).
// We keep a lock-free ring of decoded touch events; render loop drains it.
struct RawTouch { int action; int id; float x, y; };
static constexpr int kTouchRingSize = 256;
static RawTouch      g_touchRing[kTouchRingSize];
static std::atomic<int> g_touchW{0}, g_touchR{0};

static void touchRingPush(int action, int id, float x, float y) {
    int w = g_touchW.load(std::memory_order_relaxed);
    g_touchRing[w % kTouchRingSize] = {action, id, x, y};
    g_touchW.store(w + 1, std::memory_order_release);
}
static bool touchRingPop(RawTouch& out) {
    int r = g_touchR.load(std::memory_order_relaxed);
    if (r == g_touchW.load(std::memory_order_acquire)) return false;
    out = g_touchRing[r % kTouchRingSize];
    g_touchR.store(r + 1, std::memory_order_relaxed);
    return true;
}

// Evdev reader thread — a second, read-only fd on the same touch panel TouchHelperA opened.
// TouchHelperA(readOnly=true) keeps no consumer for these events (its ImGui feed is compiled out),
// so the overlay decodes MT protocol B itself and hands finished touches to the render loop.
//
// Coordinates: raw panel units go through Touch::Touch2Screen(), the same panel->screen mapping
// (touch_scale + display rotation) the old ImGui path used. Raw "value / max * W" is wrong as soon
// as the display is rotated: the panel is portrait, the overlay is landscape.
struct EvdevCtx { int fd; };
static void* evdevThread(void* arg) {
    EvdevCtx* ctx = (EvdevCtx*)arg;
    const int fd = ctx->fd;
    delete ctx;

    constexpr int kSlots = 10;
    struct Slot { float px = 0, py = 0; bool down = false, pendDown = false, pendUp = false, dirty = false; };
    Slot slots[kSlots];
    int cur = -1;                                   // -1: slot index out of range -> ignore its events

    pollfd pf{}; pf.fd = fd; pf.events = POLLIN;
    input_event evs[64];
    while (g_run) {
        // The fd is O_NONBLOCK: a plain read() on an idle panel returns EAGAIN. poll() with a timeout
        // keeps the loop alive and lets it notice g_run going false.
        int pr = poll(&pf, 1, 100);
        if (pr < 0) { if (errno == EINTR) continue; break; }
        if (pr == 0) continue;
        if (pf.revents & (POLLERR | POLLHUP | POLLNVAL)) break;

        ssize_t r = read(fd, evs, sizeof(evs));
        if (r < 0) { if (errno == EINTR || errno == EAGAIN) continue; break; }
        if (r == 0 || (r % (ssize_t)sizeof(input_event)) != 0) continue;
        size_t cnt = (size_t)r / sizeof(input_event);

        for (size_t i = 0; i < cnt; i++) {
            const input_event& ev = evs[i];
            if (ev.type == EV_ABS) {
                if (ev.code == ABS_MT_SLOT) { cur = (ev.value >= 0 && ev.value < kSlots) ? ev.value : -1; continue; }
                if (cur < 0) continue;
                Slot& s = slots[cur];
                if (ev.code == ABS_MT_TRACKING_ID) {
                    if (ev.value < 0) s.pendUp = true; else s.pendDown = true;
                } else if (ev.code == ABS_MT_POSITION_X) { s.px = (float)ev.value; s.dirty = true; }
                else if   (ev.code == ABS_MT_POSITION_Y) { s.py = (float)ev.value; s.dirty = true; }
            } else if (ev.type == EV_SYN && ev.code == SYN_REPORT) {
                // one report = one consistent frame; emit per-slot transitions in down -> move -> up order
                for (int k = 0; k < kSlots; k++) {
                    Slot& s = slots[k];
                    if (!s.pendDown && !s.down && !s.pendUp) { s.dirty = false; continue; }
                    Vector2 sp = Touch::Touch2Screen(Vector2(s.px, s.py));
                    if (s.pendDown) {
                        s.pendDown = false; s.down = true; touchRingPush(0, k, sp.x, sp.y);
                        static int dbgDowns = 0;   // first taps only: shows panel -> canvas mapping without flooding the terminal
                        if (dbgDowns < 40) { dbgDowns++; EPRINT("[touch] down slot=%d panel=(%.0f,%.0f) -> canvas=(%.0f,%.0f) of %dx%d rot=%d\n", k, s.px, s.py, sp.x, sp.y, g_scrW, g_scrH, g_touchRot); }
                    }
                    else if (s.down && s.dirty) { touchRingPush(2, k, sp.x, sp.y); }
                    if (s.pendUp)               { s.pendUp = false; if (s.down) { s.down = false; touchRingPush(1, k, sp.x, sp.y); } }
                    s.dirty = false;
                }
            }
        }
    }
    close(fd);
    return nullptr;
}

// AIM hold button hit-test rect (top-left region, 110x110 logical px)
static bool aimBtnHit(float tx, float ty) {
    return g_cfg.aimHold && tx >= 40.f && tx <= 150.f
        && ty >= (float)g_scrH * 0.35f && ty <= (float)g_scrH * 0.35f + 110.f;
}


// injection runs off the render thread: injectLib() blocks for minutes (waits for the game, il2cpp, ptrace), and the old
// in-loop call froze drawing + touch, so the menu vanished the moment the key was accepted. ptrace stays on ONE thread (this one).
struct InjectJob { char lib[512]; bool emb; bool overlayOnly; };
static InjectJob        g_injJob;
static std::atomic<int> g_injState{0};   // 0 idle, 1 running (waiting for game / injecting), 2 done ok, 3 failed
static void* injectThread(void* a) {
    InjectJob* j = (InjectJob*)a;
    bool ok = j->overlayOnly || injectLib(j->emb ? nullptr : j->lib);
    if (!ok) EPRINT("inject failed - overlay stays up, retry on next launch or check logcat linker\n");
    g_injState.store(ok ? 2 : 3, std::memory_order_release);
    return nullptr;
}

static int runOverlay(int argc, char** argv) {
    if (!initEGL()) return 1;
    printf("[*] stage: basemenu\n");
    if (!initBaseMenu()) return 1;
    printf("[*] stage: touch\n");
    mkdir(kDataDir, 0777);   // ignore error: already exists
    cfgLoad();
    // Touch_Init sets up the panel->screen mapping (touch_scale, rotation) that evdevThread relies on via
    // Touch::Touch2Screen(); without it that mapping is uninitialised, so no touch thread is started.
    int touchFd = -1;
    bool touchOk = Touch_Init(g_scrW, g_scrH, 0, true);
    if (!touchOk) EPRINT("[!] Touch_Init failed (no MT touch device / no access to /dev/input) — menu touch disabled\n");
    // Second read-only fd for our own decoder. Same selection rule as TouchHelperA::Init
    // (first /dev/input/eventN with ABS_MT_SLOT + POSITION_X + POSITION_Y), so both agree on the panel.
    if (touchOk) {
        auto hasAbsBit = [](const uint8_t* m, int bit) { return (m[bit / 8] >> (bit % 8)) & 1; };
        char buf[64];
        for (int i = 0; i < 32 && touchFd < 0; i++) {
            snprintf(buf, sizeof(buf), "/dev/input/event%d", i);
            int fd = open(buf, O_RDONLY | O_NONBLOCK);
            if (fd < 0) continue;
            uint8_t absmask[ABS_MAX / 8 + 1] = {};
            bool ok = ioctl(fd, EVIOCGBIT(EV_ABS, sizeof(absmask)), absmask) >= 0
                   && hasAbsBit(absmask, ABS_MT_SLOT)
                   && hasAbsBit(absmask, ABS_MT_POSITION_X)
                   && hasAbsBit(absmask, ABS_MT_POSITION_Y);
            if (ok) { touchFd = fd; printf("[+] evdev: %s\n", buf); }
            else close(fd);
        }
        if (touchFd >= 0) {
            auto* ctx = new EvdevCtx{touchFd};
            pthread_t t;
            if (pthread_create(&t, nullptr, evdevThread, ctx) == 0) pthread_detach(t);
            else { EPRINT("[!] evdev thread start failed\n"); delete ctx; close(touchFd); touchFd = -1; }
        }
        if (touchFd < 0) EPRINT("[!] no MT evdev node found — menu touch will not work\n");
    }

    loadSavedKey(g_keyBuf, sizeof(g_keyBuf));
    if (g_keyBuf[0]) licStart(g_keyBuf, true);

    bool overlayOnly = argc > 1 && !strcmp(argv[1], "--overlay");
    bool injected = false;
    printf("[+] overlay up. unlock with your license key. Ctrl-C to quit.\n");

    {
        char self[256] = {};
        ssize_t n = readlink("/proc/self/exe", self, sizeof(self) - 1);
        if (n > 0) { self[n] = 0; if (!integrity::selfCheck(self)) g_run = false; }
        // readlink failing is a packaging/environment problem, not evidence of
        // tampering — leave g_run alone (same stance as selfCheck()'s own
        // unreadable-path case, see integrity.h).
    }

    // emulator/farm-device gate, fail fast before touching anything else.
    if (antivm::check() == antivm::Verdict::Suspicious) g_run = false;

    uint64_t lastOpen = 0;
    uint64_t lastAntidbg = 0;
    uint64_t lastAntivm = 0;
    int64_t  lastMs   = (int64_t)(nowMs());

    while (g_run) {
        if (nowMs() - lastAntidbg > 1000) {   // throttled: cheap, but no need to pay it every frame
            lastAntidbg = nowMs();
            if (antidbg::check() == antidbg::Verdict::Suspicious) { g_run = false; }
        }
        // re-checked periodically, not just at startup: device build-props
        // don't change, but a Magisk prop-hider module can be toggled on/off
        // live without restarting the process, and the startup gate above
        // wouldn't see that. Longer interval than antidbg (10s vs 1s) since
        // what it's watching for changes far less often, and the checks
        // themselves (property reads, a couple of file-existence checks)
        // aren't free to pay every second for no reason.
        if (nowMs() - lastAntivm > 10000) {
            lastAntivm = nowMs();
            if (antivm::check() == antivm::Verdict::Suspicious) { g_run = false; }
        }
        if (g_licensed && !injected) {
            char lib[512]; bool emb = false;
            if (!resolveLib(argc, argv, overlayOnly, lib, sizeof(lib), emb)) { g_run = false; break; }
            snprintf(g_injJob.lib, sizeof(g_injJob.lib), "%s", lib);
            g_injJob.emb = emb; g_injJob.overlayOnly = overlayOnly;
            injected = true;
            g_injState.store(1, std::memory_order_release);
            pthread_attr_t at; pthread_attr_init(&at); pthread_attr_setstacksize(&at, 4u << 20);
            pthread_t th;
            if (pthread_create(&th, &at, injectThread, &g_injJob) == 0) pthread_detach(th);
            else { EPRINT("[!] inject thread start failed\n"); g_injState.store(3, std::memory_order_release); }
            pthread_attr_destroy(&at);
        }

        if (!g_shm && nowMs() - lastOpen > 1000) { lastOpen = nowMs(); shmTryOpen(); }
        shmPoll();
        licPoll();
        Touch_UpdateImGui();   // shim: refreshes display rotation for Touch2Screen (every 30th call); name is legacy
        {
            static int lastRot = -99, lastRaw = -99;
            if (g_touchRot != lastRot || g_touchRotRaw != lastRaw) {
                lastRot = g_touchRot; lastRaw = g_touchRotRaw;
                EPRINT("[touch] rotation: display reports %d -> Touch2Screen uses %d\n", g_touchRotRaw, g_touchRot);
            }
        }

        // ── touch events → menu / lock screen / aim button ──────────────────
        {
            RawTouch ev{};
            while (touchRingPop(ev)) {
                float tx = ev.x, ty = ev.y;
                int   act = ev.action; // 0=down 1=up 2=move
                if (!g_licensed) {
                    lockScreenTouch(act, tx, ty);
                } else {
                    if (aimBtnHit(tx, ty)) {
                        if (act == 0) g_aimActive = 1;
                        else if (act == 1) g_aimActive = 0;
                    }
                    g_menu.touch(act, ev.id, tx, ty);
                }
            }
        }

        // ── compute dt ───────────────────────────────────────────────────────
        int64_t curMs = (int64_t)(nowMs());
        float dt = (float)(curMs - lastMs) * 0.001f;
        if (dt > 0.1f) dt = 0.1f;
        lastMs = curMs;

        // ── render ───────────────────────────────────────────────────────────
        g_gfx.begin(g_dw, g_dh);

        if (g_licensed) {
            g_menu.hudEnemies = g_cnt;   // HUD pill "Enemies:"
            g_menu.hudBots    = 0;       // FILL: bots are not distinguished in the entity data yet
            g_menu.render(g_gfx, dt);   // first: its begin() clears the frame and drops queued geometry
            drawEsp();
            drawAim();
            // AIM hold button visual
            if (g_cfg.aim && g_cfg.aimHold) {
                Col btnC = g_aimActive ? rgba(230,56,90,200) : rgba(30,30,40,180);
                g_gfx.rect(40.f, (float)g_scrH*0.35f, 110.f, 110.f, 14.f, btnC);
                float ts = 18.f;
                float tw = g_gfx.textWidth("AIM", ts);
                g_gfx.text(40.f+(110.f-tw)*0.5f, (float)g_scrH*0.35f+46.f, "AIM", ts, rgba(255,255,255));
            }
            if (g_injState.load(std::memory_order_acquire) == 1) g_gfx.text(40.f, 30.f, "waiting for game...", 18.f, rgba(230,230,240));
            else if (g_injState.load(std::memory_order_acquire) == 3) g_gfx.text(40.f, 30.f, "inject failed, see logcat", 18.f, rgba(230,56,90));
        } else {
            drawLockScreen(dt);
        }

        g_gfx.end();
        eglSwapBuffers(g_dpy, g_sur);
    }

    // zero payload controls before exit
    if (g_shm) { Ctl& c = g_shm->ctl; c.aim=0; c.active=0; c.esp=0; c.noSpread=0; c.skel=0; c.lead=0; c.silent=0; c.noRecoil=0; }
    eglMakeCurrent(g_dpy, EGL_NO_SURFACE, EGL_NO_SURFACE, EGL_NO_CONTEXT);
    eglDestroyContext(g_dpy, g_ctx);
    eglDestroySurface(g_dpy, g_sur);
    eglTerminate(g_dpy);
    anwc::ANativeWindowCreator::Destroy(g_win);
    Touch_Close();
    return 0;
}

int main(int argc, char** argv) {
    // antidbg::armSelfTrace();   // DISABLED: self PTRACE_TRACEME with shell as tracer that never wait()s -> process
                                   // gets stuck in group-stop on first signal, surfaces as segfault/"stopped jobs"
    if (geteuid() != 0) { EPRINT("need root\n"); return 1; }
    signal(SIGINT, onSig); signal(SIGTERM, onSig); signal(SIGPIPE, SIG_IGN);
    { struct sigaction sa{}; sa.sa_sigaction = crashHandler; sa.sa_flags = SA_SIGINFO | SA_RESETHAND; sigemptyset(&sa.sa_mask);
      for (int s : {SIGSEGV, SIGBUS, SIGILL, SIGABRT, SIGFPE}) sigaction(s, &sa, nullptr); }
    setvbuf(stdout, nullptr, _IONBF, 0);
    return runOverlay(argc, argv);
}
