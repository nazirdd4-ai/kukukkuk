#!/usr/bin/env bash
# pack_elf.sh — wraps a finished, stripped, hash-patched binary in stub_loader.c, producing a
# single standalone ELF (not a shell script) that decrypts+execve()s it via memfd at runtime.
# See stub_loader.c's header for the mechanism and why it's expected to clear the W^X/execmem
# wall that shelved protect.sh's UPX route — same UNVERIFIED-on-real-hardware disclosure applies
# here; this was built and sanity-checked against the NDK's own build of the stub itself in this
# session, NOT run against a device (no device/emulator available here).
#
# Run AFTER build.sh (and optionally protect.sh) have produced the final @fyxod_cpp, in the same
# strip -> shdr-drop -> integrity-patch -> [upx] -> pack_elf position. This REPLACES
# make_launcher.sh's @fyxod_cpp_run.sh for distribution; make_launcher.sh still runs too (see
# build.sh) so you keep the shell-launcher fallback for a device where memfd-exec turns out to be
# denied — ship whichever one you've actually confirmed launches on your target device.
#
# Usage: tools/pack_elf.sh <binary> <out-elf>
set -euo pipefail

BIN="${1:?usage: pack_elf.sh <binary> <out-elf>}"
OUT="${2:?usage: pack_elf.sh <binary> <out-elf>}"
[ -f "$BIN" ] || { echo "ERROR: pack_elf.sh: no such file: $BIN" >&2; exit 1; }

NDK_HOME="${NDK_HOME:-/opt/android-ndk}"
TOOLCHAIN="$NDK_HOME/toolchains/llvm/prebuilt/linux-x86_64"
CXX="$TOOLCHAIN/bin/aarch64-linux-android31-clang"   # stub_loader.c is C, not C++ — no BaseMenu/ImGui deps

SRC="$(cd "$(dirname "$0")/../src" && pwd)"
OUTDIR="$(dirname "$OUT")"
mkdir -p "$OUTDIR"

echo "[*] pack_elf: embedding $BIN ($(wc -c < "$BIN") bytes) into stub_blob.h..."
python3 - "$BIN" "$OUTDIR/stub_blob.h" <<'PYEOF'
import sys, os, struct
src, dst = sys.argv[1], sys.argv[2]
data = open(src, 'rb').read()

# Fresh random key per pack — this blob has no relationship to ENC_KEY/PL_KEY (different
# artifact, different build step); reusing either would just be a second name for the same
# number, not a reason to think it's protected any differently than PL_KEY already is.
key = struct.unpack('<Q', os.urandom(8))[0] | 1   # xorshift64 needs a nonzero seed

def xorshift64_encrypt(buf, x):
    out = bytearray(len(buf))
    for i, b in enumerate(buf):
        x ^= (x << 13) & 0xFFFFFFFFFFFFFFFF
        x ^= (x >> 7)
        x ^= (x << 17) & 0xFFFFFFFFFFFFFFFF
        out[i] = b ^ ((x >> 24) & 0xFF)
    return out

enc = xorshift64_encrypt(data, key)

with open(dst, 'w') as f:
    f.write('// generated by tools/pack_elf.sh, do not edit\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n')
    f.write('static const uint64_t STUB_KEY = 0x%016xULL;\nstatic const size_t STUB_LEN = %d;\n' % (key, len(enc)))
    f.write('static const uint8_t STUB_BLOB[] = {\n')
    for i in range(0, len(enc), 24):
        f.write(','.join(str(v) for v in enc[i:i+24]) + ',\n')
    f.write('};\n')
print(f"stub_blob.h written ({len(enc)} bytes embedded)")
PYEOF

echo "[*] pack_elf: compiling stub (arm64)..."
"$CXX" -O2 -fvisibility=hidden -fPIE -pie -Wall -Wextra -Wno-unused-parameter \
    -I"$OUTDIR" -std=c17 \
    "$SRC/stub_loader.c" \
    -Wl,--gc-sections \
    -o "$OUT"

"$TOOLCHAIN/bin/llvm-strip" --strip-all "$OUT"
python3 "$(dirname "$0")/strip_shdrs.py" "$OUT"

echo "[+] pack_elf: done: $OUT ($(wc -c < "$OUT") bytes), wraps $BIN ($(wc -c < "$BIN") bytes)"
echo "[!] UNVERIFIED on real hardware this session — confirm \$OUT launches and the menu comes up"
echo "    before shipping this over the make_launcher.sh @fyxod_cpp_run.sh fallback. If execve()"
echo "    fails with EACCES specifically, check logcat -b events | grep avc for an execmem/memfd"
echo "    SELinux denial — that's the one realistic failure mode stub_loader.c's header names."
