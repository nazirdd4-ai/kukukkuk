#!/usr/bin/env bash
# make_launcher.sh — wraps a binary into a self-extracting @fyxod_cpp_run.sh
# Usage: make_launcher.sh <binary-in> <launcher-out>
# Split out of build.sh so it can be re-run by the CI "protect" step AFTER strip/upx —
# running it only once, before upx touches the binary, would bake stale pre-upx bytes
# into the launcher while the separately-uploaded raw binary is the post-upx one.
set -euo pipefail

BIN="${1:?usage: make_launcher.sh <binary-in> <launcher-out>}"
LAUNCHER="${2:?usage: make_launcher.sh <binary-in> <launcher-out>}"
[ -f "$BIN" ] || { echo "ERROR: make_launcher.sh: no such file: $BIN" >&2; exit 1; }

# ── self-extracting launcher ─────────────────────────────────────────────────
# Single file to push to the device: a POSIX shell header (runs under Android's /system/bin/sh,
# which has neither `base64` nor `openssl` as a rule) followed by the payload as \NNN octal
# escapes, decoded with `printf '%b'`. Fed one bounded-size line at a time, NOT as one giant
# argument: on at least one real device `printf` turned out to be the external /system/bin/printf,
# not a shell builtin, so a single multi-hundred-KB argument blows execve()'s ARG_MAX ("Argument
# list too long"). Each line here is a fixed number of \NNN groups, comfortably under any
# plausible ARG_MAX, so the loop stays correct regardless of whether printf is a builtin or not.
# Octal, not \xHH: \xHH is a bash/mksh printf extension, NOT POSIX — a strict /bin/sh (dash, and
# possibly toybox) leaves "\x41" as the literal 4 characters instead of decoding it.
echo "[*] writing launcher..."
{
    cat <<'LAUNCHER_HEAD'
#!/system/bin/sh
# self-extracting launcher for @fyxod_cpp — do not edit by hand, regenerated by make_launcher.sh
set -e
PAYLOAD_LINE=__PAYLOAD_LINE__
# decode next to this script, not into /data/local/tmp: on modern Android that path is often
# mounted noexec for anything that isn't shell/root (adb shell gets away with it, a regular app
# like Termux usually doesn't) — chmod +x succeeds, exec fails with "Permission denied". the
# directory this script itself ran from has already proven it allows exec, so reuse it.
SELFDIR=$(cd "$(dirname "$0")" && pwd)
OUTBIN="$SELFDIR/.@fyxod_cpp.$$"
# sweep leftovers from prior runs that got SIGKILL'd / OOM-killed (trap below never ran for those)
for f in "$SELFDIR"/.@fyxod_cpp.*; do
    [ -f "$f" ] && [ "$f" != "$OUTBIN" ] && rm -f "$f"
done
cleanup() { rm -f "$OUTBIN"; }
trap cleanup EXIT INT TERM
: > "$OUTBIN"
tail -n "+$PAYLOAD_LINE" "$0" | while IFS= read -r chunk || [ -n "$chunk" ]; do
    printf '%b' "$chunk" >> "$OUTBIN"
done
chmod 755 "$OUTBIN"
exec "$OUTBIN" "$@"
LAUNCHER_HEAD
    echo "__PAYLOAD_BELOW__"
} > "$LAUNCHER"

# PAYLOAD_LINE must point at the first payload line (1-indexed): header lines + the
# "__PAYLOAD_BELOW__" marker line itself + 1.
HEADER_LINES=$(grep -n '^__PAYLOAD_BELOW__$' "$LAUNCHER" | tail -1 | cut -d: -f1)
PAYLOAD_LINE=$((HEADER_LINES + 1))
sed -i "s/__PAYLOAD_LINE__/$PAYLOAD_LINE/" "$LAUNCHER"

# 2000 raw bytes (8000 escape chars) per line — far under any real ARG_MAX, and each line is a
# whole number of \NNN groups so a newline never lands mid-escape.
od -An -v -to1 "$BIN" | tr -s ' ' '\n' | grep -v '^$' | awk '{printf "\\%03d", $1} NR % 2000 == 0 {print ""}' >> "$LAUNCHER"
echo >> "$LAUNCHER"   # final newline in case the byte count isn't a multiple of 2000
chmod 755 "$LAUNCHER"

echo "[+] done: $LAUNCHER ($(wc -c < "$LAUNCHER") bytes) — push this single file and run it"
